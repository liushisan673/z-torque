"""Windows single-user desktop entrypoint.

The launcher keeps mutable state under the current user's application-data directory,
runs Alembic migrations before starting FastAPI, and exposes the bundled Console on localhost.
"""

from __future__ import annotations

import asyncio
import logging
import socket
import os
import runpy
import secrets
import shutil
import socket
import sys
import webbrowser
from logging.handlers import RotatingFileHandler
from pathlib import Path


def resource_path(relative: str) -> Path:
    """Resolve immutable packaged resources, never relative to the caller's CWD."""
    root = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent))
    return root / relative


def _data_dir() -> Path:
    if os.name == "nt":
        base = Path(os.environ.get("LOCALAPPDATA") or (Path.home() / "AppData" / "Local"))
    elif sys.platform == "darwin":
        base = Path.home() / "Library" / "Application Support"
    else:
        base = Path(os.environ.get("XDG_DATA_HOME") or (Path.home() / ".local" / "share"))
    return (base / "ZTorque").expanduser().resolve()


def _read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if key.strip():
            values[key.strip()] = value.strip()
    return values


def _write_env(path: Path, values: dict[str, str]) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        "# Generated by Z-Torque desktop launcher. Keep this file private.\n"
        + "".join(f"{key}={value}\n" for key, value in sorted(values.items())),
        encoding="utf-8",
    )
    temporary.replace(path)
    try:
        path.chmod(0o600)
    except OSError:
        # Windows permissions are inherited from the per-user AppData directory.
        pass


def _prepare_environment() -> tuple[Path, bool]:
    data_dir = _data_dir()
    data_dir.mkdir(parents=True, exist_ok=True)
    for name in ("files", "secrets", "logs", "backups"):
        (data_dir / name).mkdir(parents=True, exist_ok=True)

    md_skills_dir = data_dir / "md-skills"
    if not md_skills_dir.exists():
        packaged_skills = resource_path("md-skills")
        if packaged_skills.is_dir():
            shutil.copytree(packaged_skills, md_skills_dir)
        else:
            md_skills_dir.mkdir(parents=True, exist_ok=True)

    from cryptography.fernet import Fernet
    from sqlalchemy.engine import URL

    database_file = data_dir / "z_torque.db"
    env_file = data_dir / "desktop.env"
    values = _read_env(env_file)
    if "JWT_SECRET_KEY" not in values:
        values["JWT_SECRET_KEY"] = secrets.token_urlsafe(48)
    if "SECRET_STORE_KEY" not in values:
        values["SECRET_STORE_KEY"] = Fernet.generate_key().decode("ascii")
    if "ADMIN_INITIAL_PASSWORD" not in values:
        values["ADMIN_INITIAL_PASSWORD"] = secrets.token_urlsafe(18)
    values.setdefault("ADMIN_INITIAL_USERNAME", "admin")
    values.setdefault(
        "DATABASE_URL",
        URL.create("sqlite", database=str(database_file)).render_as_string(hide_password=False),
    )
    values.setdefault("FILE_STORAGE_DIR", str(data_dir / "files"))
    values.setdefault("SECRET_STORE_DIR", str(data_dir / "secrets"))
    values.setdefault("MD_SKILLS_DIR", str(md_skills_dir))
    values.setdefault("APP_ENV", "production")
    values.setdefault("APP_DEBUG", "false")
    values.setdefault("LOG_LEVEL", "INFO")
    values.setdefault("APP_HOST", "127.0.0.1")
    values.setdefault("APP_PORT", "0")
    values.setdefault("MD_SKILL_SCRIPT_ENABLED", "true")
    values.setdefault("MD_SKILL_WINDOWS_PROCESS_ENABLED", "true")
    values.setdefault("SANDBOX_ISOLATION_MODE", "process")
    _write_env(env_file, values)

    # The desktop distribution is intentionally local-only. Resource paths are installation-specific
    # and therefore refreshed on every launch rather than persisted in desktop.env.
    for key, value in values.items():
        # 桌面配置是此安装实例的权威配置，不能被用户机器上遗留的开发环境变量劫持。
        os.environ[key] = value
    os.environ["APP_ENV"] = "production"
    os.environ["APP_DEBUG"] = "false"
    os.environ["APP_HOST"] = "127.0.0.1"
    os.environ["SERVE_CONSOLE"] = "true"
    os.environ["CONSOLE_DIST_DIR"] = str(resource_path("console/dist"))
    os.environ.setdefault("COOKIE_SECURE", "false")
    return data_dir, not database_file.exists()


def _run_migrations() -> None:
    from alembic import command
    from alembic.config import Config

    ini_path = resource_path("alembic.ini")
    config = Config(str(ini_path))
    config.set_main_option("script_location", str(resource_path("alembic")))
    command.upgrade(config, "head")


def _write_first_run_credentials(data_dir: Path, username: str, password: str) -> None:
    path = data_dir / "first-run-admin.txt"
    path.write_text(
        "Z-Torque 首次启动管理员凭据\n"
        "访问地址：首次启动后浏览器会自动打开本地控制台。\n"
        f"用户名：{username}\n"
        f"初始密码：{password}\n\n"
        "请首次登录后立即修改密码，并妥善保管此文件。\n",
        encoding="utf-8",
    )


def _rotate_bootstrap_password(data_dir: Path) -> None:
    """管理员账号已创建后，轮换仅用于 init_admin 的引导密码，避免长期保留真实初始密码。"""
    env_file = data_dir / "desktop.env"
    values = _read_env(env_file)
    values["ADMIN_INITIAL_PASSWORD"] = secrets.token_urlsafe(18)
    _write_env(env_file, values)
    os.environ["ADMIN_INITIAL_PASSWORD"] = values["ADMIN_INITIAL_PASSWORD"]


def _worker_mode() -> bool:
    # Frozen builds use the same onedir executable as the Python worker. This branch must run
    # before importing app.main so the child process never starts the web server.
    if len(sys.argv) < 3 or sys.argv[1] != "--zt-sandbox-worker":
        return False
    script_path = Path(sys.argv[2]).expanduser().resolve()
    sys.argv = [str(script_path)]
    sys.path.insert(0, str(script_path.parent))
    runpy.run_path(str(script_path), run_name="__main__")
    return True


def _self_check(data_dir: Path) -> int:
    required = (
        resource_path("alembic.ini"),
        resource_path("alembic"),
        resource_path("alembic/versions"),
        resource_path("app/builtin_plugins/audit_export_archive/migrations"),
        resource_path("console/dist/index.html"),
    )
    missing = [str(path) for path in required if not path.exists()]
    if missing:
        print("Z-Torque package is incomplete:")
        for path in missing:
            print(f"  - {path}")
        return 2
    from app.main import app  # noqa: F401

    print(f"Z-Torque desktop package check passed. Data directory: {data_dir}")
    return 0


async def _serve(data_dir: Path) -> None:
    import uvicorn

    from app.main import app
    from app.config import get_settings

    settings = get_settings()
    host = "127.0.0.1"
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    try:
        # 直接把已绑定的 socket 交给 Uvicorn，避免“探测空闲端口后关闭，再启动”
        # 之间被其他本地进程抢占的竞态。
        sock.bind((host, settings.app_port))
        sock.listen(2048)
        sock.setblocking(False)
        port = int(sock.getsockname()[1])
        url = f"http://{host}:{port}/"
        config = uvicorn.Config(
            app,
            host=host,
            port=port,
            log_level=settings.log_level.lower(),
            access_log=True,
            log_config=None,
        )
        server = uvicorn.Server(config)
        serving = asyncio.create_task(server.serve(sockets=[sock]))
        while not server.started and not serving.done():
            await asyncio.sleep(0.1)
        if server.started:
            print(f"Z-Torque 已启动：{url}")
            print(f"数据目录：{data_dir}")
            print(f"日志目录：{data_dir / 'logs'}")
            webbrowser.open_new_tab(url)
        await serving
    finally:
        sock.close()


def _acquire_instance_lock(data_dir: Path):
    """同一 Windows 用户只允许一个桌面实例操作同一份 SQLite 数据库。"""
    lock_file = (data_dir / "z-torque.instance.lock").open("a+b")
    try:
        if os.name == "nt":
            import msvcrt

            lock_file.seek(0, os.SEEK_END)
            if lock_file.tell() == 0:
                lock_file.write(b"0")
                lock_file.flush()
            lock_file.seek(0)
            msvcrt.locking(lock_file.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl

            fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        return lock_file
    except (OSError, BlockingIOError):
        lock_file.close()
        raise RuntimeError("Z-Torque is already running for this user") from None



def main() -> int:
    if _worker_mode():
        return 0

    data_dir, _ = _prepare_environment()
    instance_lock = _acquire_instance_lock(data_dir)
    log_dir = data_dir / "logs"
    handlers: list[logging.Handler] = [
        RotatingFileHandler(log_dir / "z-torque.log", maxBytes=10 * 1024 * 1024, backupCount=5, encoding="utf-8")
    ]
    if sys.stdout is not None:
        handlers.append(logging.StreamHandler(sys.stdout))
    logging.basicConfig(level=logging.INFO, handlers=handlers, format="%(asctime)s %(levelname)s %(name)s %(message)s")

    try:
        if "--self-check" in sys.argv:
            return _self_check(data_dir)

        _run_migrations()
        from app.cli import init_admin
        from app.config import get_settings
        from app.db.session import SessionLocal
        from app.models import User
        from sqlalchemy import select

        settings = get_settings()
        with SessionLocal() as db:
            admin_exists = db.scalar(
                select(User.id).where(User.username == settings.admin_initial_username).limit(1)
            ) is not None
        init_admin()
        if not admin_exists:
            password = settings.admin_initial_password
            if hasattr(password, "get_secret_value"):
                password = password.get_secret_value()
            _write_first_run_credentials(data_dir, settings.admin_initial_username, str(password))
        _rotate_bootstrap_password(data_dir)

        asyncio.run(_serve(data_dir))
        return 0
    except KeyboardInterrupt:
        return 0
    except Exception:
        logging.getLogger("z_torque.desktop").exception("Z-Torque desktop startup failed")
        print(f"启动失败。请查看日志：{log_dir / 'z-torque.log'}")
        return 1
    finally:
        instance_lock.close()


if __name__ == "__main__":
    raise SystemExit(main())
