# 类别 → 动作集合反查表：category 查询参数按 action IN 过滤
ACTIONS_BY_CATEGORY: dict[str, tuple[str, ...]] = {}
for _action, _category in AUDIT_CATEGORY_BY_ACTION.items():
    ACTIONS_BY_CATEGORY.setdefault(_category, ())
    ACTIONS_BY_CATEGORY[_category] = (*ACTIONS_BY_CATEGORY[_category], _action)

CATEGORIES: tuple[str, ...] = tuple(sorted(ACTIONS_BY_CATEGORY))


def audit_category(action: str) -> str:
    """action → category；未登记动作兜底"配置变更"。"""
    return AUDIT_CATEGORY_BY_ACTION.get(action, DEFAULT_CATEGORY)


def actions_for_category(category: str) -> tuple[str, ...]:
    """category → 动作集合；未知类别返回空集（查询语义为"无匹配"）。"""
    return ACTIONS_BY_CATEGORY.get(category, ())
